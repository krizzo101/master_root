#!/usr/bin/env python3
"""
Log Analysis Utilities for Debug GenericOrchestrator

Provides tools to analyze the comprehensive debug logs generated by the enhanced orchestrator,
including performance analysis, bottleneck identification, dependency flow analysis,
and execution timeline generation.
"""

import json
import re
from collections import defaultdict, Counter
from datetime import datetime, timedelta
from pathlib import Path
from typing import Dict, List, Any, Optional, Tuple
import statistics


class LogAnalyzer:
    """Comprehensive log analyzer for debug orchestrator logs"""
    
    def __init__(self, log_dir: Path):
        self.log_dir = Path(log_dir)
        if not self.log_dir.exists():
            raise ValueError(f"Log directory does not exist: {log_dir}")
        
        # Find log files
        self.debug_logs = list(self.log_dir.glob("debug_*.log"))
        self.values_logs = list(self.log_dir.glob("values_*.jsonl"))
        self.performance_logs = list(self.log_dir.glob("performance_*.log"))
        
        # Parsed data caches
        self._values_cache = None
        self._performance_cache = None
        self._debug_cache = None

    def get_log_summary(self) -> Dict[str, Any]:
        """Get basic summary of available logs"""
        return {
            "log_directory": str(self.log_dir),
            "debug_logs": len(self.debug_logs),
            "values_logs": len(self.values_logs),
            "performance_logs": len(self.performance_logs),
            "debug_log_files": [f.name for f in self.debug_logs],
            "values_log_files": [f.name for f in self.values_logs],
            "performance_log_files": [f.name for f in self.performance_logs],
            "total_log_size_mb": sum(f.stat().st_size for f in self.log_dir.glob("*.log*")) / (1024 * 1024)
        }

    def parse_values_logs(self, force_refresh: bool = False) -> List[Dict]:
        """Parse all values logs into structured data"""
        if self._values_cache is not None and not force_refresh:
            return self._values_cache
        
        values_data = []
        for log_file in self.values_logs:
            try:
                with open(log_file, 'r') as f:
                    for line_no, line in enumerate(f, 1):
                        line = line.strip()
                        if line:
                            try:
                                entry = json.loads(line)
                                entry['_source_file'] = log_file.name
                                entry['_line_number'] = line_no
                                values_data.append(entry)
                            except json.JSONDecodeError as e:
                                print(f"Warning: Failed to parse line {line_no} in {log_file.name}: {e}")
            except Exception as e:
                print(f"Warning: Failed to read {log_file.name}: {e}")
        
        # Sort by timestamp
        values_data.sort(key=lambda x: x.get('timestamp', ''))
        self._values_cache = values_data
        return values_data

    def parse_performance_logs(self, force_refresh: bool = False) -> List[Dict]:
        """Parse performance logs into structured data"""
        if self._performance_cache is not None and not force_refresh:
            return self._performance_cache
        
        performance_data = []
        perf_pattern = re.compile(r'(\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}\.\d{3}) \| PERF \| (.+)')
        
        for log_file in self.performance_logs:
            try:
                with open(log_file, 'r') as f:
                    for line_no, line in enumerate(f, 1):
                        match = perf_pattern.match(line.strip())
                        if match:
                            timestamp_str, perf_info = match.groups()
                            
                            # Parse performance info
                            parts = perf_info.split(' | ')
                            if len(parts) >= 2:
                                operation = parts[0]
                                duration_part = parts[1]
                                
                                # Extract duration
                                duration_match = re.search(r'duration=([0-9.]+)s', duration_part)
                                duration = float(duration_match.group(1)) if duration_match else None
                                
                                # Extract additional metrics
                                metrics = {}
                                for part in parts[2:]:
                                    if '=' in part:
                                        key, value = part.split('=', 1)
                                        metrics[key.strip()] = value.strip()
                                
                                performance_data.append({
                                    'timestamp': timestamp_str,
                                    'operation': operation,
                                    'duration': duration,
                                    'metrics': metrics,
                                    '_source_file': log_file.name,
                                    '_line_number': line_no
                                })
            except Exception as e:
                print(f"Warning: Failed to read {log_file.name}: {e}")
        
        # Sort by timestamp
        performance_data.sort(key=lambda x: x.get('timestamp', ''))
        self._performance_cache = performance_data
        return performance_data

    def analyze_token_usage(self) -> Dict[str, Any]:
        """Analyze token pool usage patterns"""
        values_data = self.parse_values_logs()
        
        token_events = [entry for entry in values_data 
                       if entry.get('context', '').startswith('TokenPool.')]
        
        acquisitions = []
        releases = []
        peak_usage = 0
        usage_over_time = []
        
        for event in token_events:
            context = event.get('context', '')
            values = event.get('values', {})
            timestamp = event.get('timestamp', '')
            
            if context == 'TokenPool.acquire.post':
                acquisitions.append({
                    'timestamp': timestamp,
                    'token_idx': values.get('acquired_token_idx'),
                    'available_after': values.get('available_count'),
                    'total_acquisitions': values.get('total_acquisitions')
                })
                
                # Track usage over time
                in_use = len(values.get('tokens_in_use', []))
                if in_use > peak_usage:
                    peak_usage = in_use
                
                usage_over_time.append({
                    'timestamp': timestamp,
                    'tokens_in_use': in_use,
                    'available': values.get('available_count', 0)
                })
            
            elif context == 'TokenPool.release.success':
                releases.append({
                    'timestamp': timestamp,
                    'token_idx': values.get('released_token_idx'),
                    'available_after': values.get('available_count'),
                    'total_releases': values.get('total_releases')
                })
        
        # Calculate statistics
        analysis = {
            'total_acquisitions': len(acquisitions),
            'total_releases': len(releases),
            'peak_concurrent_usage': peak_usage,
            'usage_over_time': usage_over_time,
            'acquisition_rate': len(acquisitions) / max(1, len(usage_over_time)) if usage_over_time else 0,
            'release_rate': len(releases) / max(1, len(usage_over_time)) if usage_over_time else 0
        }
        
        # Analyze token distribution
        if acquisitions:
            token_usage_count = Counter(acq['token_idx'] for acq in acquisitions if acq['token_idx'] is not None)
            analysis['token_distribution'] = dict(token_usage_count.most_common())
            analysis['most_used_token_idx'] = token_usage_count.most_common(1)[0] if token_usage_count else None
            analysis['token_balance'] = {
                'min_usage': min(token_usage_count.values()) if token_usage_count else 0,
                'max_usage': max(token_usage_count.values()) if token_usage_count else 0,
                'avg_usage': statistics.mean(token_usage_count.values()) if token_usage_count else 0
            }
        
        return analysis

    def analyze_dependency_flow(self) -> Dict[str, Any]:
        """Analyze dependency resolution patterns"""
        values_data = self.parse_values_logs()
        
        dependency_events = [entry for entry in values_data 
                           if entry.get('context', '').startswith('DependencyManager.')]
        
        can_run_checks = []
        state_transitions = []
        deadlock_analyses = []
        
        for event in dependency_events:
            context = event.get('context', '')
            values = event.get('values', {})
            timestamp = event.get('timestamp', '')
            
            if context == 'DependencyManager.can_run.decision':
                can_run_checks.append({
                    'timestamp': timestamp,
                    'task_id': values.get('task_id'),
                    'can_run': values.get('can_run'),
                    'unmet_dependencies': values.get('unmet_dependencies', []),
                    'failed_dependencies': values.get('failed_dependencies', []),
                    'met_dependencies': values.get('met_dependencies', [])
                })
            
            elif context == 'DependencyManager.state_transition':
                state_transitions.append({
                    'timestamp': timestamp,
                    'task_id': values.get('task_id'),
                    'old_state': values.get('old_state'),
                    'new_state': values.get('new_state'),
                    'action': values.get('action')
                })
            
            elif context == 'DependencyManager.deadlock_analysis':
                deadlock_analyses.append({
                    'timestamp': timestamp,
                    'pending_tasks': values.get('pending_tasks', []),
                    'potential_deadlocks': values.get('potential_deadlocks', []),
                    'circular_dependencies': values.get('circular_dependencies', [])
                })
        
        # Calculate statistics
        analysis = {
            'total_can_run_checks': len(can_run_checks),
            'total_state_transitions': len(state_transitions),
            'total_deadlock_checks': len(deadlock_analyses),
            'success_rate': len([c for c in can_run_checks if c['can_run']]) / max(1, len(can_run_checks)) * 100,
            'blocking_reasons': Counter(),
            'state_transition_flow': defaultdict(int)
        }
        
        # Analyze blocking reasons
        for check in can_run_checks:
            if not check['can_run']:
                if check['unmet_dependencies']:
                    analysis['blocking_reasons']['unmet_dependencies'] += 1
                if check['failed_dependencies']:
                    analysis['blocking_reasons']['failed_dependencies'] += 1
        
        # Analyze state transitions
        for transition in state_transitions:
            flow = f"{transition['old_state']} -> {transition['new_state']}"
            analysis['state_transition_flow'][flow] += 1
        
        # Deadlock analysis
        if deadlock_analyses:
            latest_deadlock = deadlock_analyses[-1]
            analysis['latest_deadlock_analysis'] = {
                'potential_deadlocks_count': len(latest_deadlock.get('potential_deadlocks', [])),
                'circular_dependencies_count': len(latest_deadlock.get('circular_dependencies', [])),
                'pending_tasks_count': len(latest_deadlock.get('pending_tasks', []))
            }
        
        return analysis

    def analyze_performance_bottlenecks(self) -> Dict[str, Any]:
        """Identify performance bottlenecks from logs"""
        performance_data = self.parse_performance_logs()
        
        if not performance_data:
            return {'error': 'No performance data available'}
        
        # Group by operation type
        operations = defaultdict(list)
        for entry in performance_data:
            operation = entry.get('operation', 'unknown')
            duration = entry.get('duration')
            if duration is not None:
                operations[operation].append(duration)
        
        # Calculate statistics for each operation
        operation_stats = {}
        for op, durations in operations.items():
            operation_stats[op] = {
                'count': len(durations),
                'total_time': sum(durations),
                'avg_time': statistics.mean(durations),
                'min_time': min(durations),
                'max_time': max(durations),
                'median_time': statistics.median(durations),
                'std_dev': statistics.stdev(durations) if len(durations) > 1 else 0
            }
        
        # Identify bottlenecks
        sorted_by_total = sorted(operation_stats.items(), key=lambda x: x[1]['total_time'], reverse=True)
        sorted_by_avg = sorted(operation_stats.items(), key=lambda x: x[1]['avg_time'], reverse=True)
        sorted_by_max = sorted(operation_stats.items(), key=lambda x: x[1]['max_time'], reverse=True)
        
        # Find slowest individual operations
        slowest_operations = []
        for entry in performance_data:
            if entry.get('duration'):
                slowest_operations.append({
                    'operation': entry.get('operation'),
                    'duration': entry.get('duration'),
                    'timestamp': entry.get('timestamp'),
                    'metrics': entry.get('metrics', {})
                })
        slowest_operations.sort(key=lambda x: x['duration'], reverse=True)
        
        return {
            'operation_statistics': operation_stats,
            'bottlenecks': {
                'by_total_time': sorted_by_total[:5],
                'by_average_time': sorted_by_avg[:5],
                'by_max_time': sorted_by_max[:5]
            },
            'slowest_individual_operations': slowest_operations[:10],
            'total_operations': len(performance_data),
            'unique_operations': len(operations),
            'total_measured_time': sum(entry.get('duration', 0) for entry in performance_data)
        }

    def generate_execution_timeline(self, task_filter: Optional[str] = None) -> Dict[str, Any]:
        """Generate execution timeline with task lifecycle events"""
        values_data = self.parse_values_logs()
        
        # Filter orchestrator events
        orchestrator_events = [entry for entry in values_data 
                             if entry.get('context', '').startswith('GenericOrchestrator.')]
        
        if task_filter:
            orchestrator_events = [event for event in orchestrator_events 
                                 if task_filter in str(event.get('values', {}).get('task_id', ''))]
        
        timeline = []
        task_lifecycles = defaultdict(list)
        
        for event in orchestrator_events:
            context = event.get('context', '')
            values = event.get('values', {})
            timestamp = event.get('timestamp', '')
            task_id = values.get('task_id', 'unknown')
            
            # Create timeline entry
            entry = {
                'timestamp': timestamp,
                'context': context,
                'task_id': task_id,
                'event_data': values
            }
            timeline.append(entry)
            task_lifecycles[task_id].append(entry)
        
        # Analyze task lifecycles
        task_analysis = {}
        for task_id, events in task_lifecycles.items():
            if task_id == 'unknown':
                continue
                
            # Find key lifecycle events
            start_event = next((e for e in events if 'start' in e['context']), None)
            complete_event = next((e for e in events if 'complete' in e['context']), None)
            
            lifecycle_analysis = {
                'total_events': len(events),
                'lifecycle_events': [e['context'] for e in events],
                'start_time': start_event['timestamp'] if start_event else None,
                'end_time': complete_event['timestamp'] if complete_event else None
            }
            
            # Calculate duration if both start and end are available
            if start_event and complete_event:
                try:
                    start_dt = datetime.fromisoformat(start_event['timestamp'].replace('Z', '+00:00'))
                    end_dt = datetime.fromisoformat(complete_event['timestamp'].replace('Z', '+00:00'))
                    lifecycle_analysis['duration_seconds'] = (end_dt - start_dt).total_seconds()
                except Exception:
                    lifecycle_analysis['duration_seconds'] = None
            
            # Extract final status
            if complete_event:
                lifecycle_analysis['final_status'] = complete_event['event_data'].get('final_status')
                lifecycle_analysis['error'] = complete_event['event_data'].get('error')
            
            task_analysis[task_id] = lifecycle_analysis
        
        return {
            'timeline': timeline,
            'task_lifecycles': dict(task_lifecycles),
            'task_analysis': task_analysis,
            'total_events': len(timeline),
            'unique_tasks': len([t for t in task_lifecycles.keys() if t != 'unknown']),
            'timeline_span': {
                'start': timeline[0]['timestamp'] if timeline else None,
                'end': timeline[-1]['timestamp'] if timeline else None
            }
        }

    def analyze_orchestrator_metrics(self) -> Dict[str, Any]:
        """Analyze overall orchestrator performance metrics"""
        values_data = self.parse_values_logs()
        
        # Find orchestrator summary events
        summary_events = [entry for entry in values_data 
                         if 'final_summary' in entry.get('context', '') or 
                            'execute_batch.complete' in entry.get('context', '')]
        
        if not summary_events:
            return {'error': 'No orchestrator summary data found'}
        
        latest_summary = summary_events[-1] if summary_events else None
        
        analysis = {
            'summary_events_found': len(summary_events),
            'latest_summary': latest_summary.get('values', {}) if latest_summary else None
        }
        
        # Analyze batch execution patterns
        batch_events = [entry for entry in values_data 
                       if 'execute_batch' in entry.get('context', '')]
        
        batch_rounds = []
        for event in batch_events:
            context = event.get('context', '')
            values = event.get('values', {})
            
            if 'round' in context and 'batch_round' in values:
                batch_rounds.append({
                    'round': values.get('batch_round'),
                    'ready_count': values.get('ready_count', 0),
                    'timestamp': event.get('timestamp')
                })
        
        if batch_rounds:
            analysis['batch_execution'] = {
                'total_rounds': max(br['round'] for br in batch_rounds),
                'rounds_data': batch_rounds,
                'avg_tasks_per_round': statistics.mean([br['ready_count'] for br in batch_rounds])
            }
        
        return analysis

    def generate_comprehensive_report(self, output_file: Optional[Path] = None) -> Dict[str, Any]:
        """Generate comprehensive analysis report"""
        
        print("Generating comprehensive log analysis report...")
        
        report = {
            'analysis_timestamp': datetime.now().isoformat(),
            'log_summary': self.get_log_summary(),
            'token_usage_analysis': self.analyze_token_usage(),
            'dependency_flow_analysis': self.analyze_dependency_flow(),
            'performance_bottlenecks': self.analyze_performance_bottlenecks(),
            'orchestrator_metrics': self.analyze_orchestrator_metrics()
        }
        
        # Generate timeline for first few tasks
        timeline_analysis = self.generate_execution_timeline()
        if timeline_analysis.get('unique_tasks', 0) > 0:
            # Limit timeline to first 5 tasks for readability
            task_ids = list(timeline_analysis['task_analysis'].keys())[:5]
            limited_timeline = self.generate_execution_timeline()
            report['execution_timeline_sample'] = {
                'sample_task_count': len(task_ids),
                'timeline_analysis': limited_timeline
            }
        
        # Add summary insights
        insights = []
        
        # Token usage insights
        token_analysis = report['token_usage_analysis']
        if token_analysis.get('peak_concurrent_usage', 0) > 0:
            insights.append(f"Peak concurrent token usage: {token_analysis['peak_concurrent_usage']}")
        
        # Performance insights
        perf_analysis = report['performance_bottlenecks']
        if perf_analysis.get('bottlenecks', {}).get('by_total_time'):
            top_bottleneck = perf_analysis['bottlenecks']['by_total_time'][0]
            insights.append(f"Top performance bottleneck: {top_bottleneck[0]} ({top_bottleneck[1]['total_time']:.2f}s total)")
        
        # Dependency insights
        dep_analysis = report['dependency_flow_analysis']
        if dep_analysis.get('success_rate'):
            insights.append(f"Dependency check success rate: {dep_analysis['success_rate']:.1f}%")
        
        report['key_insights'] = insights
        
        # Save to file if requested
        if output_file:
            output_file.parent.mkdir(parents=True, exist_ok=True)
            with open(output_file, 'w') as f:
                json.dump(report, f, indent=2, default=str)
            print(f"Report saved to: {output_file}")
        
        return report

    def print_summary(self):
        """Print a human-readable summary of the analysis"""
        
        print("\\n" + "="*60)
        print("DEBUG ORCHESTRATOR LOG ANALYSIS SUMMARY")
        print("="*60)
        
        # Log summary
        log_summary = self.get_log_summary()
        print(f"\\nLOG FILES:")
        print(f"  Debug logs: {log_summary['debug_logs']}")
        print(f"  Values logs: {log_summary['values_logs']}")
        print(f"  Performance logs: {log_summary['performance_logs']}")
        print(f"  Total size: {log_summary['total_log_size_mb']:.1f} MB")
        
        # Token usage
        print(f"\\nTOKEN USAGE:")
        token_analysis = self.analyze_token_usage()
        print(f"  Total acquisitions: {token_analysis['total_acquisitions']}")
        print(f"  Total releases: {token_analysis['total_releases']}")
        print(f"  Peak concurrent usage: {token_analysis['peak_concurrent_usage']}")
        
        # Performance
        print(f"\\nPERFORMANCE:")
        perf_analysis = self.analyze_performance_bottlenecks()
        if 'error' not in perf_analysis:
            print(f"  Total operations measured: {perf_analysis['total_operations']}")
            print(f"  Total measured time: {perf_analysis['total_measured_time']:.2f}s")
            if perf_analysis['bottlenecks']['by_total_time']:
                top = perf_analysis['bottlenecks']['by_total_time'][0]
                print(f"  Top bottleneck: {top[0]} ({top[1]['total_time']:.2f}s)")
        
        # Dependencies
        print(f"\\nDEPENDENCY MANAGEMENT:")
        dep_analysis = self.analyze_dependency_flow()
        print(f"  Total dependency checks: {dep_analysis['total_can_run_checks']}")
        print(f"  Success rate: {dep_analysis['success_rate']:.1f}%")
        print(f"  State transitions: {dep_analysis['total_state_transitions']}")
        
        print("\\n" + "="*60)


def analyze_orchestrator_logs(log_dir: Path, output_file: Optional[Path] = None) -> Dict[str, Any]:
    """Convenience function to analyze orchestrator logs"""
    analyzer = LogAnalyzer(log_dir)
    return analyzer.generate_comprehensive_report(output_file)


if __name__ == "__main__":
    import sys
    
    if len(sys.argv) < 2:
        print("Usage: python log_analyzer.py <log_directory> [output_file]")
        sys.exit(1)
    
    log_dir = Path(sys.argv[1])
    output_file = Path(sys.argv[2]) if len(sys.argv) > 2 else None
    
    try:
        analyzer = LogAnalyzer(log_dir)
        analyzer.print_summary()
        
        if output_file:
            report = analyzer.generate_comprehensive_report(output_file)
            print(f"\\nDetailed report saved to: {output_file}")
        else:
            print(f"\\nTo generate detailed report, run:")
            print(f"python {sys.argv[0]} {log_dir} report.json")
            
    except Exception as e:
        print(f"Error analyzing logs: {e}")
        sys.exit(1)