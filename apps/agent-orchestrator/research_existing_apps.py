#!/usr/bin/env python3
"""
App Research Orchestration
Using our own orchestrator to research existing apps for useful orchestration features
"""

import asyncio
import sys
from pathlib import Path

# Add the orchestrator to the path
orchestrator_path = Path("/home/opsvi/master_root/apps/agent-orchestrator")
sys.path.insert(0, str(orchestrator_path))

from src.generic_orchestrator import AgentTask, GenericOrchestrator


async def research_existing_apps():
    """
    Use our orchestrator to research existing apps for features we can borrow
    """
    print("🔬 ORCHESTRATOR RESEARCH PROJECT")
    print("=" * 60)
    print("Using agent orchestration to research existing apps for useful features")
    print()

    # Apps to research
    apps_to_research = [
        ("cc_dev_tool", "claude code development tool"),
        ("claude_dev_tool", "claude development utilities"),
        ("claude-monitor", "claude monitoring system"),
        ("hecaton", "complex multi-agent framework"),
        ("razer", "unknown utility"),
        ("tetra", "unknown utility"),
        ("multi-agent-monitor", "multi-agent monitoring system"),
    ]

    # Create orchestrator
    orchestrator = GenericOrchestrator(
        output_dir=Path("./research_output"),
        max_parallel=len(apps_to_research),  # Run all in parallel
        use_optimizations=True,
    )

    # Research context for agents
    research_context = """
    RESEARCH OBJECTIVE: We are building an enhanced agent orchestration system with these planned features:

    FEATURES WE'RE BUILDING:
    - Complex dependency management with quality gates
    - Resource conflict detection and prevention
    - Real-time agent health monitoring with context usage tracking
    - Inter-agent communication and result sharing
    - Automatic handoff when agents hit context limits
    - Phase-based execution with timed gates
    - Production-ready orchestration for 6+ parallel agents
    - Integration testing and rollback capabilities

    YOUR TASK: Analyze the assigned app and report:
    1. Any orchestration/coordination features we should borrow
    2. Monitoring/dashboard functionality that could be integrated
    3. Agent communication or management capabilities
    4. Testing/validation frameworks we could adapt
    5. Configuration management or resource handling
    6. Specific code files or classes that would be valuable to integrate

    Focus on PRODUCTION-READY functionality that could enhance our orchestration system.
    """

    # Create research tasks
    tasks = []
    for i, (app_name, description) in enumerate(apps_to_research):
        task = AgentTask(
            task_id=f"research_{app_name}",
            task_type="research",
            prompt=f"""
Research the app at /home/opsvi/master_root/apps/{app_name} for functionality useful to our orchestration system.

App: {app_name} ({description})

{research_context}

Provide a structured report with:
- Executive Summary: Key findings in 2-3 sentences
- Useful Features: Specific functionality we should integrate
- Code Assets: Particular files/classes to examine further
- Integration Recommendations: How to best leverage this app's capabilities
- Priority Level: HIGH/MEDIUM/LOW for integration importance

Be thorough but concise. Focus on ACTIONABLE findings.
            """.strip(),
        )
        tasks.append(task)

    print(f"📋 Launching {len(tasks)} research agents in parallel...")
    print("Apps under investigation:")
    for app_name, description in apps_to_research:
        print(f"   • {app_name} - {description}")
    print()

    # Execute research in parallel
    start_time = asyncio.get_event_loop().time()
    await orchestrator.execute_batch(tasks)
    end_time = asyncio.get_event_loop().time()

    duration = end_time - start_time
    print(f"\n🎯 Research completed in {duration:.1f} seconds")
    print("Check research_output/ directory for detailed findings from each agent")

    # Generate summary report
    await generate_research_summary(tasks)


async def generate_research_summary(tasks):
    """Generate a summary of all research findings"""
    summary_file = Path("research_output/RESEARCH_SUMMARY.md")

    summary_content = """# App Research Summary

## Research Objective
Investigate existing apps in /home/opsvi/master_root/apps/ for functionality that could enhance our agent orchestration system.

## Apps Researched
"""

    for task in tasks:
        app_name = task.task_id.replace("research_", "")
        summary_content += (
            f"- **{app_name}**: Research assigned to agent `{task.task_id}`\n"
        )

    summary_content += """
## Research Findings
Check individual agent reports in research_output/tasks/ directory for detailed findings.

## Next Steps
1. Review all agent reports
2. Prioritize integration opportunities
3. Plan implementation of high-priority features
4. Test integrated functionality

Generated by orchestrator research project.
"""

    with open(summary_file, "w") as f:
        f.write(summary_content)

    print(f"📄 Research summary saved to: {summary_file}")


if __name__ == "__main__":
    print("🚀 Starting orchestrated app research...")
    asyncio.run(research_existing_apps())
